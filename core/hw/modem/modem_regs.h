/* The registers, 0x00 to 0x20, as bytes (modem_regs[]); a field of one
 * is its register and the bits it has there */
#define MODEM_REGS 0x21
#define MR00 0x00				/* Receive Data Buffer (RBUFFER) */
/* 01 VOLUME VPAUSE - - TXHF RXHF RXP */
#define MR01_RXHF 0x01, 0x02
#define MR01_TXHF 0x01, 0x04
/* 02 TDE SQDIS S511 - RTSDE V54TE V54AE V54PE / DCDEN CDEN - - CODBITS */
#define MR02_RTSDE 0x02, 0x08
#define MR02_TDE 0x02, 0x40
/* 03 EPT SEPT SRCEN RLSDE - - GTE GTS */
#define MR03_RLSDE 0x03, 0x10
/* 04 RB - - FIFOEN - NRZIEN/VAGC TOD STRN */
#define MR04_FIFOEN 0x04, 0x10
/* 05 - - - TXSQ CEQ - STOFF - */
#define MR05_CEQ 0x05, 0x08
/* 06 - EXOS CCRTN HDLC PEN STB WDSZ/DECBITS */
#define MR06_PEN 0x06, 0x08
#define MR06_HDLC 0x06, 0x10
/* 07 RDLE RDL L2ACT - L3ACT - RA MHLD */
#define MR07_RDLE 0x07, 0x80
/* 08 ASYN TPDM V21S V54T V54A V54P RTRN RTS */
#define MR08_RTS 0x08, 0x01
#define MR08_TPDM 0x08, 0x40
#define MR08_ASYN 0x08, 0x80
/* 09 NV25 CC DTMF ORG LL DATA RRTSE DTR */
#define MR09_DTR 0x09, 0x01
#define MR09_DATA 0x09, 0x04
#define MR09_DTMF 0x09, 0x20
/* 0B TONEA TONEB TONEC ATV25 ATBEL - DISDET EQMAT */
#define MR0B_ATV25 0x0b, 0x10
#define MR0B_TONEC 0x0b, 0x20
#define MR0B_TONEB 0x0b, 0x40
#define MR0B_TONEA 0x0b, 0x80
/* 0C AADET ACDET CADET CCDET SDET SNDET RXFNE RSEQ */
#define MR0C_RXFNE 0x0c, 0x02
/* 0D P2DET PNDET S1DET SCR1 U1DET - TXFNF - */
#define MR0D_TXFNF 0x0d, 0x02
/* 0E RTDET BRKD RREDT SPEED(5) */
#define MR0E_SPEED_MASK 0x1f
/* 0F RLSD FED CTS DSR RI TM RTSDT V54DT */
#define MR0F_RTSDT 0x0f, 0x02
#define MR0F_RI 0x0f, 0x08
#define MR0F_DSR 0x0f, 0x10
#define MR0F_CTS 0x0f, 0x20
#define MR0F_FED 0x0f, 0x40
#define MR0F_RLSD 0x0f, 0x80
#define MR10 0x10				/* Transmit Data Buffer (TBUFFER) */
/* 11 BRKS PARSL(2) TXV RXV V23HDX TEOF TXP */
#define MR11_PARSL(v) (((v) >> 5) & 3)
#define MR12 0x12				/* Configuration (CONF) */
/* 13 TXCLK(2) RTH(2) TLVL(4) */
#define MR13_TLVL_MASK 0x0f
#define MR14 0x14				/* ABCODE */
/* 15 SLEEP STOP RDWK HWRWK AUTO RREN EXL3 EARC */
#define MR15_AUTO 0x15, 0x08
#define MR15_HWRWK 0x15, 0x10
#define MR15_RDWK 0x15, 0x20
#define MR16 0x16				/* Secondary Receive Data Buffer (SECRXB) */
#define MR17 0x17				/* Secondary Transmit Data Buffer (SECTXB) */
/* 18, 19 Memory Access Data LSB, MSB (MEDAL, MEDAM): a word */
/* 1A SFRES RIEN RION DMAE - SCOBF SCIBE SECEN */
#define MR1A_SCIBE 0x1a, 0x02
#define MR1A_SFRES 0x1a, 0x80
/* 1C Memory Access Address Low B7-B0 (MEADDL)
 * 1D MEACC - MEMW MEMCR Memory Access Address High B11-B8 (MEADDH) */
#define MR1D_MEMADD_H_MASK 0x0f
#define MR1D_MEMW 0x1d, 0x20
#define MR1D_MEACC 0x1d, 0x80
/* 1E TDBIA RDBIA TDBIE - TDBE RDBIE - RDBF */
#define MR1E_RDBF 0x1e, 0x01
#define MR1E_RDBIE 0x1e, 0x04
#define MR1E_TDBE 0x1e, 0x08
#define MR1E_TDBIE 0x1e, 0x20
#define MR1E_RDBIA 0x1e, 0x40
#define MR1E_TDBIA 0x1e, 0x80
/* 1F NSIA NCIA - NSIE NEWS NCIE - NEWC */
#define MR1F_NEWC 0x1f, 0x01
#define MR1F_NCIE 0x1f, 0x04
#define MR1F_NEWS 0x1f, 0x08
#define MR1F_NSIE 0x1f, 0x10
#define MR1F_NCIA 0x1f, 0x40
#define MR1F_NSIA 0x1f, 0x80

